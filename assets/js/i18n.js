(function () {
  const html = document.documentElement;
  const btn = document.getElementById('lang');
  const KEY = 'rm-lang';

  function apply(lang) {
    const d = DICT[lang] || DICT.pt;
    document.querySelectorAll('[data-i18n]').forEach(function (el) {
      const k = el.getAttribute('data-i18n');
      if (Object.prototype.hasOwnProperty.call(d, k)) {
        el.textContent = d[k];
      } else {
        console.warn('[i18n] missing key:', k, 'for lang:', lang);
      }
    });
    html.lang = lang === 'en' ? 'en' : 'pt-BR';
    if (btn) {
      btn.querySelector('.lang__on').textContent  = lang === 'en' ? 'EN' : 'PT';
      btn.querySelector('.lang__off').textContent = lang === 'en' ? 'PT' : 'EN';
      btn.setAttribute('aria-label', lang === 'en' ? 'Mudar para português' : 'Switch to English');
    }
    try { localStorage.setItem(KEY, lang); } catch (e) {}
  }

  let current = 'pt';
  try { current = localStorage.getItem(KEY) || 'pt'; } catch (e) {}
  if (current === 'en') apply('en');

  if (btn) {
    btn.addEventListener('click', function () {
      current = current === 'en' ? 'pt' : 'en';
      apply(current);
    });
  }
})();
